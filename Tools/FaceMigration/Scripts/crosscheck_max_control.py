"""用当前 Max 场景抽检一个代表的控制，并把结果与 UE 目标对比。

参数来自任务配置的 `crosscheck` 段（或 `Characters/<角色>/crosscheck.json`）。流程：
1. 生成参数化 MaxScript 到 `Current/Temp/crosscheck_<name>.ms`；
2. 通过 `Scripts/max_run.ps1` 交给运行中的 3ds Max（Max 自己把采样写成 JSON，不经过人工转录）；
3. UE 侧用独立实例驱动同一控制，采同名骨骼；
4. 按 `(x, -y, z)` / `(x, -y, z, w)` 换算后比较，写 `max_crosscheck_<name>.json`。

Max 未启动或写文件失败时写 `skipped` 报告，不修改资产、不伪造通过。
"""

# Shared package paths: reference inputs are read-only; reports go to the target project.
from face_paths import (tool_path as _fm_tool, read_path as _fm_read, output_path as _fm_output,
                        asset_path as _fm_asset, load_asset as _fm_load_asset, runtime_path as _fm_runtime)
import sys as _fm_sys
_fm_sys.dont_write_bytecode = True
import datetime
import json
import math
from pathlib import Path
import shutil
import string
import subprocess
import unreal

from face_paths import PACKAGE_ROOT, context

E = _fm_output(_fm_tool('Docs/Evidence'))
E.mkdir(parents=True, exist_ok=True)
PACKAGE_SCRIPTS = PACKAGE_ROOT / 'Scripts'
CATALOG = json.loads((PACKAGE_ROOT / 'Characters' / context().character / 'face-controls.json').read_text(encoding='utf-8'))
TARGET = _fm_asset(CATALOG['target']['control_rig'])

DEFAULTS = {
    'name': 'representative',
    'max_channel': 'position',
    'max_controller_index': 2,
    'max_axis': 1,
    'ui_axis': 2,
    'ui_scale': 1.0,
    'tolerance': {'primary_position_cm': 0.05, 'primary_rotation_deg': 0.15},
}

MAX_TEMPLATE = string.Template(r'''-- generated by crosscheck_max_control.py
(
  if (toLower (substituteString (maxFilePath + maxFileName) "\\" "/")) != (toLower "$EXPECTED_SCENE") do throw "Source scene mismatch; refusing sampling"
  local required = #($REQUIRED_CONTROLS)
  for nm in required do (
    local matches = getNodeByName nm all:true exact:true
    if matches.count != 1 do throw ("Missing or ambiguous source control: " + nm)
  )
  at time 0f with animate off (
  local names = #($BONES)
  local node = getNodeByName "$MAX_NODE"
  if node == undefined do throw "Missing control $MAX_NODE"
  local slot = node.$CHANNEL.controller[$INDEX]
  if slot == undefined do throw "Missing $CHANNEL controller $INDEX on $MAX_NODE"
  local orig = slot.value
  local head = getNodeByName "$MORPH_NODE"
  local mor = if head == undefined then undefined else head.modifiers[#Morpher]
  local mprops = if mor == undefined then #() else getPropNames mor
  local morig = for nm in mprops collect (try (getProperty mor nm) catch 0)
  local ss = stringStream ""
  format "{\"scene\":\"%\",\"frame\":0,\"units\":\"%\",\"system_scale\":%,\"controls_verified\":%,\"node\":\"$MAX_NODE\",\"channel\":\"$CHANNEL\",\"rows\":[" (maxFileName as string) units.SystemType units.SystemScale required.count to:ss
  local values = #($VALUES)
  local first = true
  local sampleError = undefined
  try (for value in values do (
    local v = [0.0,0.0,0.0]
    v[$AXIS1] = value
    slot.value = v
    completeRedraw()
    if not first do format "," to:ss
    first = false
    format "{\"value\":%,\"bones\":{" value to:ss
    local bfirst = true
    for nm in names do (
      local b = getNodeByName nm
      if not bfirst do format "," to:ss
      bfirst = false
      if b == undefined then (format "\"%\":null" nm to:ss) else (
        local t = b.objectTransform
        local q = t.rotation
        format "\"%\":{\"p\":[%,%,%],\"q\":[%,%,%,%]}" nm t.translation.x t.translation.y t.translation.z q.x q.y q.z q.w to:ss
      )
    )
    format "}}" to:ss
  )) catch (sampleError = getCurrentException())
  format "]," to:ss
  slot.value = orig
  completeRedraw()
  local readback = slot.value
  local changed = 0
  for i = 1 to mprops.count do (
    local nm = mprops[i]
    try (if (getProperty mor nm) != morig[i] then (setProperty mor nm morig[i]; changed += 1)) catch()
  )
  local after = for nm in mprops collect (try (getProperty mor nm) catch 0)
  local bad = for i = 1 to mprops.count where (try (after[i] != morig[i]) catch false) collect mprops[i]
  if sampleError != undefined do throw sampleError
  if (distance readback orig) > 0.00001 or bad.count != 0 do throw "Source restoration failed"
  format "\"restore\":{\"value\":[%,%,%],\"input_error\":%,\"morph_changed\":%,\"morph_unrestored_count\":%}}" readback.x readback.y readback.z (distance readback orig) changed bad.count to:ss
  (ss as string)
  )
)
''')


def settings():
    raw = dict(DEFAULTS)
    path = PACKAGE_ROOT / 'Characters' / context().character / 'crosscheck.json'
    if path.is_file():
        raw.update(json.loads(path.read_text(encoding='utf-8')))
    job_path = PACKAGE_ROOT / 'Jobs' / (context().job_id + '.json')
    if job_path.is_file():
        raw.update(json.loads(job_path.read_text(encoding='utf-8-sig')).get('crosscheck', {}))
    for key in ('control', 'max_node', 'bones', 'max_values'):
        if key not in raw:
            raise ValueError(f'缺少抽检参数 crosscheck.{key}；请在任务配置或 Characters/<角色>/crosscheck.json 中提供')
    raw.setdefault('morph_node', 'Seven_Head')
    raw.setdefault('max_channel', 'position')
    raw.setdefault('max_controller_index', 2)
    raw.setdefault('max_axis', 1)
    raw.setdefault('ui_axis', 2)
    raw['ui_scale'] = float(raw.get('ui_scale', 1.0))
    raw.setdefault('primary_bone', raw['bones'][0])
    raw.setdefault('tolerance', DEFAULTS['tolerance'])
    return raw


def render_max_script(cfg):
    from face_paths import source_path
    return MAX_TEMPLATE.substitute(
        EXPECTED_SCENE=source_path('max_scene').as_posix(),
        REQUIRED_CONTROLS=','.join(json.dumps(b['max_name'], ensure_ascii=False)
                                   for b in CATALOG['bindings'] if b.get('enabled', True)),
        BONES=','.join(f'"{b}"' for b in cfg['bones']),
        MAX_NODE=cfg['max_node'], CHANNEL=cfg['max_channel'],
        INDEX=int(cfg['max_controller_index']), AXIS1=int(cfg['max_axis']) + 1,
        MORPH_NODE=cfg['morph_node'],
        VALUES=','.join(repr(float(v)) for v in cfg['max_values']))


def run_max(script_path):
    """Run the generated MaxScript through the package client; return (ok, stdout, error)."""
    pwsh = shutil.which('pwsh') or shutil.which('powershell')
    if not pwsh:
        return False, '', 'pwsh/powershell not found'
    command = [pwsh, '-NoProfile', '-File', str(PACKAGE_SCRIPTS / 'max_run.ps1'),
               '-ScriptFile', str(script_path), '-Job', context().job_id,
               '-ProjectRoot', str(context().project)]
    try:
        done = subprocess.run(command, capture_output=True, text=True, timeout=240)
    except Exception as exc:
        return False, '', f'{type(exc).__name__}: {exc}'
    output = (done.stdout or '') + (done.stderr or '')
    if done.returncode != 0:
        return False, output, (done.stderr or output)[-2000:]
    return True, output, ''


def extract_json(output):
    """Max returns the sample JSON as the command result; pick the payload out of the client log."""
    start = output.find('{')
    end = output.rfind('}')
    if start < 0 or end <= start:
        raise ValueError('Max 输出里没有 JSON 载荷')
    return json.loads(output[start:end + 1])


def sample_ue(cfg):
    rig = _fm_load_asset(TARGET)
    assert rig, TARGET
    host = rig.get_editor_asset().create_rig_vm_host()
    host.request_init()
    h = host.get_hierarchy()
    if not h.get_all_keys():
        h.copy_hierarchy(rig.hierarchy)
        host.request_init()
    control = unreal.RigElementKey(type=unreal.RigElementType.CONTROL, name=cfg['control'])
    assert h.contains(control), '目标缺少控制 ' + cfg['control']
    rows = []
    for value in cfg['max_values']:
        h.reset_pose_to_initial(unreal.RigElementType.CONTROL)
        vector = [0.0, 0.0, 0.0]
        vector[int(cfg['ui_axis'])] = float(value) * cfg['ui_scale']
        h.set_control_value(control, h.make_control_value_from_vector(unreal.Vector(*vector)))
        assert host.execute('Forwards Solve')
        row = {'ui': vector, 'bones': {}}
        for bone in cfg['bones']:
            transform = h.get_global_transform(unreal.RigElementKey(type=unreal.RigElementType.BONE, name=bone))
            row['bones'][bone] = {
                'p': [round(v, 6) for v in transform.translation.to_tuple()],
                'q': [round(transform.rotation.x, 6), round(transform.rotation.y, 6),
                      round(transform.rotation.z, 6), round(transform.rotation.w, 6)]}
        rows.append(row)
    h.reset_pose_to_initial(unreal.RigElementType.CONTROL)
    return rows


def to_ue(value):
    return [value['p'][0], -value['p'][1], value['p'][2]], [value['q'][0], -value['q'][1], value['q'][2], value['q'][3]]


def errors(ue_row, name, max_bone):
    want_p, want_q = to_ue(max_bone)
    got_p = ue_row['bones'][name]['p']
    got_q = ue_row['bones'][name]['q']
    position = math.dist(want_p, got_p)
    dot = abs(sum(a * b for a, b in zip(want_q, got_q))) / math.sqrt(
        sum(a*a for a in want_q) * sum(b*b for b in got_q))
    dot = max(-1.0, min(1.0, dot))
    return round(position, 8), round(math.degrees(2 * math.acos(dot)), 8)


def main():
    cfg = settings()
    script_path = _fm_runtime('Temp') / f"crosscheck_{cfg['name']}.ms"
    script_path.parent.mkdir(parents=True, exist_ok=True)
    script_path.write_text(render_max_script(cfg), encoding='utf-8')
    ok, log, error = run_max(script_path)
    report = {'captured_at': datetime.datetime.now().astimezone().isoformat(),
              'character': context().character, 'job_id': context().job_id, 'target': TARGET,
              'config': {k: v for k, v in cfg.items()},
              'script': str(script_path),
              'max_command_ok': ok, 'max_log_tail': (log or '')[-4000:]}
    maxdata = None
    if ok:
        try:
            maxdata = extract_json(log)
        except Exception as exc:
            error = f'{type(exc).__name__}: {exc}'
    if maxdata is None:
        report.update(skipped=True, passed=False, max_error=error or 'no payload',
                      reason='Max 采样未完成（3ds Max 未运行、safe_mode 拦截、控件名不符或返回载荷无法解析）；本段不构成通过')
        (E / f"max_crosscheck_{cfg['name']}.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
        print(json.dumps({'skipped': True, 'reason': report['reason'], 'error': report.get('max_error')}, ensure_ascii=False))
        return
    # Keep the raw Max capture next to the report so the comparison is reproducible.
    (E / f"max_crosscheck_{cfg['name']}_max.json").write_text(json.dumps(maxdata, ensure_ascii=False, indent=2), encoding='utf-8')
    ue_rows = sample_ue(cfg)
    pairs = []
    for max_row, ue_row in zip(maxdata['rows'], ue_rows):
        pair = {'max_value': max_row['value'], 'ui': ue_row['ui'], 'bones': {}}
        for bone in cfg['bones']:
            if not max_row['bones'].get(bone):
                pair['bones'][bone] = 'missing in Max sample'
                continue
            position, rotation = errors(ue_row, bone, max_row['bones'][bone])
            pair['bones'][bone] = {'position_cm': position, 'rotation_deg': rotation}
        pairs.append(pair)
    primary = cfg['primary_bone']
    tolerance = cfg['tolerance']
    primary_rows = [p['bones'][primary] for p in pairs if isinstance(p['bones'].get(primary), dict)]
    report.update({
        'scene': maxdata.get('scene'), 'frame': maxdata.get('frame'),
        'units': maxdata.get('units'), 'system_scale': maxdata.get('system_scale'),
        'controls_verified': maxdata.get('controls_verified'),
        'mapping': {'max': f"{maxdata.get('node')}.{maxdata.get('channel')}.controller[{cfg['max_controller_index']}]"
                           f" axis {cfg['max_axis']}",
                    'ue': f"{cfg['control']} axis {cfg['ui_axis']} x {cfg['ui_scale']}",
                    'axes': 'ue = (x, -y, z) / quat (x, -y, z, w)'},
        'source_restore': maxdata.get('restore'),
        'pairs': pairs,
        'primary_bone': {'name': primary,
                         'max_position_error_cm': max((r['position_cm'] for r in primary_rows), default=0),
                         'max_rotation_error_deg': max((r['rotation_deg'] for r in primary_rows), default=0)},
        'secondary_differences': {bone: {'max_position_error_cm': max((p['bones'][bone]['position_cm'] for p in pairs
                                                                      if isinstance(p['bones'].get(bone), dict)), default=0),
                                        'max_rotation_error_deg': max((p['bones'][bone]['rotation_deg'] for p in pairs
                                                                       if isinstance(p['bones'].get(bone), dict)), default=0)}
                                  for bone in cfg['bones'] if bone != primary},
        'tolerance': tolerance,
        'skipped': False,
        'scope': 'one representative control only; the remaining controls are not recaptured from Max',
    })
    report['passed'] = len(primary_rows) == len(cfg['max_values']) and \
        len(maxdata['rows']) == len(ue_rows) == len(cfg['max_values']) and \
        maxdata.get('restore', {}).get('input_error', 1) < 1e-5 and \
        maxdata.get('restore', {}).get('morph_unrestored_count', 1) == 0 and \
        report['primary_bone']['max_position_error_cm'] < tolerance['primary_position_cm'] and \
        report['primary_bone']['max_rotation_error_deg'] < tolerance['primary_rotation_deg']
    report['skipped'] = False
    (E / f"max_crosscheck_{cfg['name']}.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps({'passed': report['passed'], 'primary': report['primary_bone'],
                      'secondary': report['secondary_differences'],
                      'restore': report['source_restore'], 'report': str(E / f"max_crosscheck_{cfg['name']}.json")},
                     ensure_ascii=False))


main()
